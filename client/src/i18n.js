export function formatMoney(amount, lang) {
  const locale = { fr: 'fr-FR', en: 'en-US', ar: 'ar-MA' }[lang] ?? 'fr-FR';
  return `${new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }).format(amount)} ${lang === 'ar' ? 'درهم' : 'MAD'}`;
}
