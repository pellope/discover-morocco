const merged = {};
export function getT(lang) {
  const code = translations[lang] ? lang : 'fr';
  if (!merged[code]) {
    merged[code] = { ...translations[code], ...EXTRA[code], errors: { ...translations[code].errors, ...EXTRA[code].extraErrors } };
  }
  return merged[code];
}

